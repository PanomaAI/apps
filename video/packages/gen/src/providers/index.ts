/*
  The providers, and the one place a name becomes one.

  Model ids move every few months in this field — two of the three below did not exist
  when this repository was started — so nothing here is a constant a caller has to
  recompile against: a provider is chosen by name, its default model is a default, and the
  price it quotes carries the date it was read.

  What differs between them is not a detail, and the table is the reason `Capability`
  exists at all:

  | | Veo 3.1 | Omni Flash | Seedance 2.0 |
  |---|---|---|---|
  | seconds | 4, 6, 8 | 3-10, extendable to 40 | 4-15 |
  | aspects | 16:9, 9:16 | 16:9, 9:16 | 21:9 … 9:16, and 1:1 |
  | first frame | yes | yes | yes |
  | last frame | yes | no | yes |
  | negative prompt | yes | **no** | **no** |
  | seed | weakly | no | yes |

  The row that decides a film: only Seedance makes a SQUARE clip, and panoma video cuts
  a square for the feed. A board rendered on Veo for `s` gets told so rather than
  quietly cropped.
*/
import type { Generator } from "../generator.ts";
import { omni, OMNI_DEFAULT, omniCapability } from "./omni.ts";
import { seedance, SEEDANCE_DEFAULT, seedanceCapability } from "./seedance.ts";
import { veo, VEO_DEFAULT, veoCapability, VEO_MODELS } from "./veo.ts";

export { omni, omniCapability, OMNI_DEFAULT } from "./omni.ts";
export { seedance, seedanceCapability, SEEDANCE_DEFAULT } from "./seedance.ts";
export { veo, veoCapability, generateVideo, VEO_DEFAULT, VEO_MODELS } from "./veo.ts";
export type { VeoRequest } from "./veo.ts";

export const PROVIDERS = ["veo", "omni", "seedance"] as const;
export type ProviderName = (typeof PROVIDERS)[number];

/** The key each provider needs, so `panoma-video doctor` can say which ones this machine can use. */
export const PROVIDER_KEYS: Record<ProviderName, string> = {
  veo: "GEMINI_API_KEY",
  omni: "GEMINI_API_KEY",
  seedance: "FAL_KEY",
};

export function generatorFor(name: ProviderName, model?: string): Generator {
  if (name === "veo") return veo(model ?? VEO_DEFAULT);
  if (name === "omni") return omni(model ?? OMNI_DEFAULT);
  return seedance(model ?? SEEDANCE_DEFAULT);
}

/**
 * What a provider can do, without opening a connection or needing a key.
 *
 * This is what prices a board and what writes the "your square cut cannot be generated by
 * this model" line, and both of those have to happen before anybody decides to spend.
 */
export function capabilityOf(name: ProviderName, model?: string) {
  if (name === "veo") return veoCapability(model ?? VEO_DEFAULT);
  if (name === "omni") return omniCapability();
  return seedanceCapability();
}

/** Every model id this repository knows a price for, for the terminal's help text. */
export const KNOWN_MODELS: Record<ProviderName, string[]> = {
  veo: Object.keys(VEO_MODELS),
  omni: [OMNI_DEFAULT],
  seedance: [SEEDANCE_DEFAULT],
};
